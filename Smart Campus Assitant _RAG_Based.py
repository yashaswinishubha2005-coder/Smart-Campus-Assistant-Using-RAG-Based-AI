@app.route("/ask", methods=["POST"])
def ask():
    try:
        user_q = request.json.get("question", "")
        if not user_q.strip():
            return jsonify({"answer": "Please ask a valid question."})

        if user_q.lower() in ["list pyq", "pyq list", "list subjects"]:
            return jsonify({"answer": list_pyq_subjects()})

        pyq_result = find_pyq_link(user_q)

        if pyq_result:
            return jsonify({"answer": pyq_result})

        response = qa_engine.query(user_q)
        answer = response.response if hasattr(response, "response") else str(response)
        return jsonify({"answer": answer})
    except Exception as e:
        return jsonify({"answer": f"Error processing RAG query: {str(e)}"})

