import re

def find_pyq_link(user_input):

    cleaned_input = re.sub(r'[^a-z0-9\s]', '', user_input.lower())

    paper_keywords = ["pyq", "previous year", "question paper", "paper", "past paper"]
    has_paper_keyword = any(word in cleaned_input for word in paper_keywords)

    if not has_paper_keyword:
        return None

    for paper in pyq_papers:
        terms_to_check = [paper["subject"].lower()] + [alias.lower() for alias in paper.get("aliases", [])]
        for term in terms_to_check:
            cleaned_term = re.sub(r'[^a-z0-9\s]', '', term)
            if cleaned_term and cleaned_term in cleaned_input:
                return f"📘 Here’s the previous year paper for {paper['subject']}:\n🔗 {paper['link']}"

    return None


def list_pyq_subjects():
    subject_list = "\n".join([
        f"- {paper['subject']} (Aliases: {', '.join(paper['aliases']) or 'None'})"
        for paper in pyq_papers
    ])
    return f"📚 Available PYQ Subjects: \n{subject_list}"

