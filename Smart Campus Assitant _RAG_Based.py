from typing import List
from pathlib import Path

def load_data_and_create_nodes() -> List[Document]:
    """Loads files, handles chunking vs. no-chunking, and returns a list of LlamaIndex Documents."""
    all_documents = []
    splitter = SentenceSplitter(chunk_size=700, chunk_overlap=100)

# chunking
    print("\n--- Processing large, narrative files (with chunking)...")
    for file_path in CHUNKING_FILES:
        try:
            docs = PDFReader().load_data(Path(file_path))
            nodes = splitter.get_nodes_from_documents(docs)
            all_documents.extend(nodes)
            print(f"   -> Chunked {os.path.basename(file_path)} into {len(nodes)} pieces.")
        except Exception as e:
            print(f"ERROR processing {os.path.basename(file_path)}: {e}")
            print("   -> Skipping this file. Please check if the PDF is corrupted or password-protected.")

# no chunking
    print("\n--- Processing structured/tabular files (loaded whole/per row)...")
    for file_path in NO_CHUNKING_FILES:
        try:
            file_name = os.path.basename(file_path)
            file_extension = os.path.splitext(file_path)[1].lower()
            docs = []

            if file_extension == ".pdf":
                docs = PDFReader().load_data(Path(file_path))
            elif file_extension == ".csv":
                docs = CSVReader(concat_rows=False).load_data(Path(file_path))

                if file_name in HEADERS:
                    header = HEADERS[file_name]
                    contextual_docs = []
                    for doc in docs:
                        new_text = f"DATA CONTEXT: {header}\nDATA ROW: {doc.text}"
                        new_doc = Document(
                            text=new_text,
                            metadata=doc.metadata,
                            excluded_llm_metadata_keys=doc.excluded_llm_metadata_keys
                        )
                        contextual_docs.append(new_doc)
                    docs = contextual_docs

            all_documents.extend(docs)
            print(f"   -> Loaded {file_name} as {len(docs)} contextual row-units.")
        except Exception as e:
            print(f"ERROR processing {os.path.basename(file_path)}: {e}")
            print("   -> Skipping this file.")

    return all_documents

